  @doc "Register every engine variable in `cvars` (`QuakeServer.Cvars.register/4`)."
  @spec register(Cvars.t()) :: Cvars.t()
  def register(%Cvars{} = cvars) do
    for {name, default, flags, second, description} <- @entries do
      Cvars.register(cvars, name, value(default),
        flags: flags,
        alias: second,
        description: description
      )
    end

    cvars
  end

  @doc "The engine variables as `{name, default, flags, second_name, description}`."
  @spec entries() :: [
          {String.t(), String.t(), [Cvars.flag()], String.t() | nil, String.t() | nil}
        ]
  def entries,
    do:
      Enum.map(@entries, fn {name, default, flags, second, description} ->
        {name, value(default), flags, second, description}
      end)

  defp value(:platform), do: platform(:os.type())
  defp value(text), do: text

  defp platform({:unix, :darwin}), do: "Mac"
  defp platform({:unix, :linux}), do: "Linux"
  defp platform({:win32, _}), do: "Win"
  defp platform(_os), do: "Unix"
