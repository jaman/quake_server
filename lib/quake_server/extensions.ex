             builtin <- builtins,
             into: %{},
             do: {builtin, module}

  @doc "Run builtin `builtin`, a number or a name, with `argc` arguments."
  @spec call(map(), integer() | String.t(), non_neg_integer()) :: map()
  def call(host, builtin, argc) do
    host = QuakeServer.EntityTable.observe(host)

    case Map.get(@table, builtin) do
      nil -> Builtins.call(host, builtin, argc)
      module -> module.call(host, builtin, argc)
    end
  end

  @doc "Whether `builtin` is one this module runs."
  @spec known?(integer() | String.t() | nil) :: boolean()
  def known?(builtin) when is_integer(builtin) and builtin in 1..78, do: true
  def known?(builtin), do: Map.has_key?(@table, builtin)
end
